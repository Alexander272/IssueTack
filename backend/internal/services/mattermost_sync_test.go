package services

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestCleanMMLastName(t *testing.T) {
	tests := []struct {
		name string
		in   string
		want string
	}{
		{"без телефона", "Иванов", "Иванов"},
		{"лишние пробелы", "  Иванов  ", "Иванов"},
		{"телефон через плюс", "Иванов +7 999 123-45-67", "Иванов"},
		{"телефон слитно", "Иванов +79991234567", "Иванов"},
		{"телефон через восьмёрку", "Иванов 8-999-123-45-67", "Иванов"},
		{"телефон с надписью", "Иванов, тел. 89991234567", "Иванов"},
		{"телефон в скобках", "Иванов (12345)", "Иванов"},
		{"два внутренних номера в скобках", "Хасанова (603, 604)", "Хасанова"},
		{"два номера в скобках через запятую", "Хасанова (603, 604, 605)", "Хасанова"},
		{"два номера через запятую вне скобок", "Хасанова, 603, 604", "Хасанова"},
		{"два номера без пробела после запятой", "Хасанова,603,604", "Хасанова"},
		{"телефон в скобках через плюс", "Иванов (+7 999 123-45-67)", "Иванов"},
		{"телефон в скобках через запятую", "Иванов, (12345)", "Иванов"},
		{"телефон в скобках через запятую и плюс", "Иванов, (+7 999 123-45-67)", "Иванов"},
		{"телефон в скобках без пробела", "Иванов,(8-999-123-45-67)", "Иванов"},
		{"телефон в скобках с надписью", "Иванов, (тел. 89991234567)", "Иванов"},
		{"скобки с внутренним номером через запятую", "Иванов Петров, (12345)", "Иванов Петров"},
		{"телефон с несколькими надписями", "Иванов тел. моб. 89991234567", "Иванов"},
		{"телефон посередине", "Иванов  +7 (999) 123-45-67  Петров", "Иванов"},
		{"двойная фамилия", "Иванов-Петров", "Иванов-Петров"},
		{"фамилия целиком телефон", "+7 999 123-45-67", "+7 999 123-45-67"},
		{"пустая строка", "", ""},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			assert.Equal(t, tt.want, cleanMMLastName(tt.in))
		})
	}
}

func TestBuildFIOWithCleanMMLastName(t *testing.T) {
	sysFio := buildFIO("Пётр", "Иванов")
	mmFio := buildFIO("Пётр", cleanMMLastName("Иванов +7 999 123-45-67"))

	assert.Equal(t, "пётр иванов", sysFio)
	assert.Equal(t, sysFio, mmFio, "системный пользователь должен совпадать по ФИО с MM-пользователем с телефоном в фамилии")
}
